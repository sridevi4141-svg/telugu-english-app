function createLanguageSelector() {

    // Already exists అయితే duplicate చేయకూడదు
    if (document.getElementById("commonLanguageSelector")) {
        return;
    }

    const wrapper = document.createElement("div");

    wrapper.id = "commonLanguageSelector";

    wrapper.innerHTML = `
        <div class="common-language-box">

            <span class="language-globe">🌐</span>

            <select id="commonLanguageSelect">
                <option value="en">English</option>
                <option value="te">తెలుగు</option>
            </select>

        </div>
    `;

    document.body.appendChild(wrapper);

    const select =
        document.getElementById("commonLanguageSelect");

    // Current language select చేయడం
    const currentLanguage = lang();

    select.value = currentLanguage;

    // Language change
    select.addEventListener("change", function () {

        changeLanguage(this.value);

        // Dropdown value update
        this.value = this.value;
    });
}