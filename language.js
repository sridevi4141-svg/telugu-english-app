const TE = {};
Object.entries(EN).forEach(([en, te]) => { TE[te] = en; });

function lang(){ return localStorage.getItem(LANGUAGE_KEY) || "en"; }
function normalize(s){ return String(s || "").replace(/\s+/g, " ").trim(); }
function mapText(value, language){
    const key = normalize(value);
    const dict = language === "te" ? EN : TE;

    if (Object.prototype.hasOwnProperty.call(dict, key)) {
        return dict[key];
    }

    // Dynamic Day titles: Day 1 Customers <-> రోజు 1 కస్టమర్లు
    let match = key.match(/^Day\s+(\d+)\s+Customers$/i);
    if (language === "te" && match) return `రోజు ${match[1]} కస్టమర్లు`;
    match = key.match(/^రోజు\s+(\d+)\s+కస్టమర్లు$/);
    if (language === "en" && match) return `Day ${match[1]} Customers`;

    // Dynamic Week title: Week 1 <-> వారం 1
    match = key.match(/^Week\s+(\d+)$/i);
    if (language === "te" && match) return `వారం ${match[1]}`;
    match = key.match(/^వారం\s+(\d+)$/);
    if (language === "en" && match) return `Week ${match[1]}`;

    return value;
}

function translateTextNode(node, language){
    const parent = node.parentElement;
    if (!parent || ["SCRIPT","STYLE","CODE","PRE"].includes(parent.tagName)) return;
    const original = node.nodeValue;
    const translated = mapText(original, language);
    if (translated !== original) node.nodeValue = translated;
}

function translateElement(el, language){
    if (el.dataset && el.dataset.i18n) {
        const key = el.dataset.i18n;
        const translated = language === "te" ? EN[key] : TE[EN[key]];
        if (translated) el.textContent = translated;
    }
    if (el.placeholder) {
        const translated = mapText(el.placeholder, language);
        if (translated !== el.placeholder) el.placeholder = translated;
    }
    if (el.title) {
        const translated = mapText(el.title, language);
        if (translated !== el.title) el.title = translated;
    }
    if (el.value && ["button","submit","reset"].includes((el.type || "").toLowerCase())) {
        const translated = mapText(el.value, language);
        if (translated !== el.value) el.value = translated;
    }
}

function translateTree(language){
    document.documentElement.lang = language === "te" ? "te" : "en";
    document.title = mapText(document.title, language);
    document.querySelectorAll("*").forEach(el => {
        translateElement(el, language);
        for (const node of [...el.childNodes]) {
            if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, language);
        }
    });
}

window.changeLanguage = function(language){
    const selected = language === "te" ? "te" : "en";
    localStorage.setItem(LANGUAGE_KEY, selected);
    translateTree(selected);
};
window.getFinanceLanguage = lang;

function translateSubtree(root, language){
    if (!root || root.nodeType !== Node.ELEMENT_NODE) return;
    translateElement(root, language);
    root.querySelectorAll("*").forEach(el => translateElement(el, language));
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    nodes.forEach(node => translateTextNode(node, language));
}

const observer = new MutationObserver(mutations => {
    const language = lang();
    if (language !== "te" && language !== "en") return;
    for (const mutation of mutations) {
        mutation.addedNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE) {
                translateTextNode(node, language);
            } else if (node.nodeType === Node.ELEMENT_NODE && !["SCRIPT","STYLE"].includes(node.tagName)) {
                translateSubtree(node, language);
            }
        });
    }
    if (typeof updateLanguageLabel === "function") updateLanguageLabel();
});

document.addEventListener("DOMContentLoaded", () => {
    const selected = localStorage.getItem(LANGUAGE_KEY);
    const isStartPage = /(^|\/)index\.html$/i.test(window.location.pathname) ||
        window.location.pathname === "/" || window.location.pathname === "";

    // Language is selected only once on the first page.
    // All other pages use the saved choice automatically.
    if (!selected && !isStartPage) {
        window.location.href = "index.html";
        return;
    }

    if (selected) translateTree(selected);
    observer.observe(document.body, {childList:true, subtree:true});

     createLanguageSelector();
});

window.selectStartLanguage = function(language) {

    const selected = language === "te" ? "te" : "en";

    // Save selected language
    localStorage.setItem("financeLanguage", selected);
    localStorage.setItem("financeLanguageChosen", "true");

    // Apply language immediately
    translateTree(selected);

    // Hide language selection
    const chooser =
        document.getElementById("startLanguageChooser");

    // Show main application
    const app =
        document.getElementById("mainAppContent");

    if (chooser) {
        chooser.classList.add("hidden-language-chooser");
    }

    if (app) {
        app.classList.remove("app-hidden-until-language");
    }
};

