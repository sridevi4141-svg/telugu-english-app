const TE = {};
Object.entries(EN).forEach(([en, te]) => { TE[te] = en; });

function lang(){ return localStorage.getItem(LANGUAGE_KEY) || "en"; }
function normalize(s){ return String(s || "").replace(/\s+/g, " ").trim(); }
function mapText(value, language){
    const key = normalize(value);
    const dict = language === "te" ? EN : TE;
    return Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : value;
}

function translateTextNode(node, language){
    const parent = node.parentElement;
    if (!parent || ["SCRIPT","STYLE","CODE","PRE"].includes(parent.tagName)) return;
    const original = node.nodeValue;
    const translated = mapText(original, language);
    if (translated !== original) node.nodeValue = translated;
}

function translateElement(el, language){
    if (el.dataset && el.dataset.i18n) {
        const key = el.dataset.i18n;
        const translated = language === "te" ? EN[key] : TE[EN[key]];
        if (translated) el.textContent = translated;
    }
    if (el.placeholder) {
        const translated = mapText(el.placeholder, language);
        if (translated !== el.placeholder) el.placeholder = translated;
    }
    if (el.title) {
        const translated = mapText(el.title, language);
        if (translated !== el.title) el.title = translated;
    }
    if (el.value && ["button","submit","reset"].includes((el.type || "").toLowerCase())) {
        const translated = mapText(el.value, language);
        if (translated !== el.value) el.value = translated;
    }
}

function translateTree(language){
    document.documentElement.lang = language === "te" ? "te" : "en";
    document.title = mapText(document.title, language);
    document.querySelectorAll("[data-language-select]").forEach(s => s.value = language);
    document.querySelectorAll("*").forEach(el => {
        translateElement(el, language);
        for (const node of [...el.childNodes]) {
            if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, language);
        }
    });
}

window.changeLanguage = function(language){
    const selected = language === "te" ? "te" : "en";
    localStorage.setItem(LANGUAGE_KEY, selected);
    translateTree(selected);
};
window.getFinanceLanguage = lang;

function addLanguageBar(){
    if (document.querySelector("[data-language-select]")) return;
    const bar = document.createElement("div");
    bar.className = "finance-global-language";
    bar.innerHTML = `<label>🌐 <span class="finance-language-label">Language:</span></label><select data-language-select aria-label="Language"><option value="en">English</option><option value="te">తెలుగు</option></select>`;
    bar.querySelector("select").addEventListener("change", e => window.changeLanguage(e.target.value));
    document.body.prepend(bar);
}

function updateLanguageLabel(){
    document.querySelectorAll(".finance-language-label").forEach(el => {
        el.textContent = lang() === "te" ? "భాష:" : "Language:";
    });
}

const observer = new MutationObserver(mutations => {
    const language = lang();
    for (const mutation of mutations) {
        mutation.addedNodes.forEach(node => {
            if (node.nodeType === Node.TEXT_NODE) translateTextNode(node, language);
            else if (node.nodeType === Node.ELEMENT_NODE && !["SCRIPT","STYLE"].includes(node.tagName)) {
                translateElement(node, language);
                node.querySelectorAll?.("*").forEach(el => translateElement(el, language));
            }
        });
    }
    updateLanguageLabel();
});

document.addEventListener("DOMContentLoaded", () => {
    addLanguageBar();
    translateTree(lang());
    updateLanguageLabel();
    observer.observe(document.body, {childList:true, subtree:true});
});
